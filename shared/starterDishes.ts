import type { Heat, Slot } from './types'

export interface StarterDish {
  key: string
  name: string
  mealTypes: Slot[]
  heat: Heat
  tags: string[]
  cookMinutes: number
}

function slug(s: string): string {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function d(
  name: string,
  mealTypes: Slot[],
  heat: Heat,
  tags: string[],
  cookMinutes: number,
): StarterDish {
  return { key: slug(name), name, mealTypes, heat, tags, cookMinutes }
}

